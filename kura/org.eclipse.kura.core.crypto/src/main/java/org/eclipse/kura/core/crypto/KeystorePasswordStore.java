package org.eclipse.kura.core.crypto;

import java.io.IOException;
import java.io.InputStream;
import java.nio.channels.Channels;
import java.nio.channels.FileChannel;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.nio.file.attribute.BasicFileAttributes;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.Objects;
import java.util.Properties;

/** Ciphertext-only persistence. Rotation across provider files requires its own stopped-Core transaction. */
class KeystorePasswordStore {
    // Multiple CryptoService instances in the same JVM must not lose each other's entries.
    private static final Object UPDATE_LOCK = new Object();

    void put(Path file, String key, String ciphertext) throws IOException {
        synchronized (UPDATE_LOCK) {
            Path target = file.toAbsolutePath().normalize();
            BasicFileAttributes original = state(target);
            Properties values = new Properties();
            if (original != null) {
                try (InputStream input = Files.newInputStream(target, LinkOption.NOFOLLOW_LINKS)) {
                    values.load(input);
                } catch (IllegalArgumentException invalid) {
                    throw new IOException("Malformed keystore password file; original retained", invalid);
                }
                unchanged(target, original);
            }
            values.setProperty(key, ciphertext);

            Path staged = null;
            try (FileChannel directory = FileChannel.open(target.getParent(), StandardOpenOption.READ)) {
                // Refuse a filesystem that cannot sync the directory before modifying its contents.
                directory.force(true);
                staged = Files.createTempFile(target.getParent(), ".store-save-", ".tmp",
                        PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rw-------")));
                try (FileChannel output = FileChannel.open(staged, StandardOpenOption.WRITE, LinkOption.NOFOLLOW_LINKS)) {
                    values.store(Channels.newOutputStream(output), "Do not edit this file. It's automatically generated by Kura");
                    output.force(true);
                }
                unchanged(target, original);
                publish(staged, target);
                directory.force(true);
            } finally {
                if (staged != null) {
                    Files.deleteIfExists(staged);
                }
            }
        }
    }

    // Kept separate to exercise a failed atomic publication against real files.
    void publish(Path staged, Path target) throws IOException {
        Files.move(staged, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
    }

    private static BasicFileAttributes state(Path path) throws IOException {
        final BasicFileAttributes attributes;
        try {
            attributes = Files.readAttributes(path, BasicFileAttributes.class, LinkOption.NOFOLLOW_LINKS);
        } catch (NoSuchFileException missing) {
            return null;
        }
        if (!attributes.isRegularFile()
                || ((Number) Files.getAttribute(path, "unix:nlink", LinkOption.NOFOLLOW_LINKS)).longValue() != 1) {
            throw new IOException("Keystore password file must be a single-link regular file");
        }
        return attributes;
    }

    private static void unchanged(Path path, BasicFileAttributes expected) throws IOException {
        BasicFileAttributes current = state(path);
        if (expected == null ? current != null
                : current == null || !Objects.equals(expected.fileKey(), current.fileKey())
                        || expected.size() != current.size()
                        || !expected.lastModifiedTime().equals(current.lastModifiedTime())
                        || !expected.creationTime().equals(current.creationTime())) {
            throw new IOException("Keystore password file changed; publication refused");
        }
    }
}
