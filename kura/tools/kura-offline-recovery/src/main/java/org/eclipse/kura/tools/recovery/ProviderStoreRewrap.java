package org.eclipse.kura.tools.recovery;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Properties;

import org.eclipse.kura.core.crypto.CryptoServiceImpl;

/** Ciphertext-only adapter for CryptoService's Java Properties store. The caller owns publication. */
public final class ProviderStoreRewrap {
    private static final int MAX_BYTES = 1024 * 1024;
    private static final int MAX_RECORDS = 4096;

    private ProviderStoreRewrap() { }

    public static void main(String[] args) {
        try {
            if (args.length != 2 || !args[1].matches("[0-9a-f]{64}")) {
                throw new IllegalArgumentException();
            }
            var crypto = RecoveryCrypto.loadManaged(Path.of("/etc/kura/credentials"), args[0], args[1]);
            byte[] input = System.in.readNBytes(MAX_BYTES + 1);
            System.out.write(rewrap(input, crypto, args[0]));
            System.out.flush();
            if (System.out.checkError()) {
                throw new IOException();
            }
        } catch (Exception failed) {
            System.err.println("PROVIDER_STORE_REWRAP_FAILED");
            System.exit(2);
        }
    }

    static byte[] rewrap(byte[] original, CryptoServiceImpl crypto, String activeSha256) throws Exception {
        if (original.length > MAX_BYTES || !activeSha256.matches("[0-9a-f]{64}")) {
            throw new IllegalArgumentException();
        }
        var properties = new Properties() {
            @Override
            public synchronized Object put(Object key, Object value) {
                if (containsKey(key) || size() >= MAX_RECORDS) {
                    throw new IllegalArgumentException();
                }
                return super.put(key, value);
            }
        };
        properties.load(new ByteArrayInputStream(original));
        var result = new Properties();
        String activePrefix = "KURA2." + activeSha256 + ".";
        boolean changed = false;
        for (String name : properties.stringPropertyNames()) {
            String ciphertext = properties.getProperty(name);
            // CryptoService preserves empty values, including older explicitly empty properties.
            char[] plain = crypto.decryptAes(ciphertext.toCharArray());
            try {
                if (!ciphertext.isEmpty() && !ciphertext.startsWith(activePrefix)) {
                    char[] encrypted = crypto.encryptAes(plain);
                    try {
                        String wrapped = new String(encrypted);
                        if (!wrapped.startsWith(activePrefix)) {
                            throw new IOException();
                        }
                        ciphertext = wrapped;
                        changed = true;
                    } finally {
                        Arrays.fill(encrypted, '\0');
                    }
                }
                result.setProperty(name, ciphertext);
            } finally {
                Arrays.fill(plain, '\0');
            }
        }
        if (!changed) {
            return original;
        }
        var output = new ByteArrayOutputStream();
        result.store(output, "Do not edit this file. It's automatically generated by Kura");
        if (output.size() > MAX_BYTES) {
            throw new IOException();
        }
        return output.toByteArray();
    }
}
